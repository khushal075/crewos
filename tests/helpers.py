class MemoryRedis:
    """Minimal isolated ownership-store fake; live Redis is tested separately."""

    def __init__(self):
        self.values = {}

    def set(self, key, value, ex=None, nx=False):
        if nx and key in self.values:
            return False
        self.values[key] = value
        return True

    def get(self, key):
        return self.values.get(key)
